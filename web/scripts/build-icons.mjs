import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

// Builds a same-origin SVG symbol sprite and TypeScript union type from local `web/icons/*.svg`
// (official Lucide ISC static icons rendered at `stroke-width="1.5"`).
const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(__dirname, '..');
const iconsSrcDir = path.join(rootDir, 'icons');

const spriteOut = path.join(rootDir, 'src/assets/icons-sprite.svg');
const typesOut = path.join(rootDir, 'src/icons/names.ts');

if (!fs.existsSync(iconsSrcDir)) {
  console.error(`[build-icons] Local icon directory not found: ${iconsSrcDir}`);
  process.exit(1);
}

const files = fs
  .readdirSync(iconsSrcDir)
  .filter((f) => f.endsWith('.svg'))
  .sort();

if (files.length === 0) {
  console.error(`[build-icons] No .svg files found in ${iconsSrcDir}`);
  process.exit(1);
}

const names = [];
const symbols = [];

for (const file of files) {
  const name = file.slice(0, -'.svg'.length);
  const raw = fs.readFileSync(path.join(iconsSrcDir, file), 'utf8');
  const openMatch = raw.match(/<svg\b[^>]*>/i);
  const closeIdx = raw.lastIndexOf('</svg>');
  if (!openMatch || closeIdx < 0) {
    console.error(`[build-icons] Failed to parse SVG file: ${file}`);
    process.exit(1);
  }
  const viewBoxMatch = openMatch[0].match(/viewBox="([^"]+)"/i);
  const viewBox = viewBoxMatch ? viewBoxMatch[1] : '0 0 24 24';
  const inner = raw
    .slice(openMatch.index + openMatch[0].length, closeIdx)
    .trim()
    .replace(/\s*\n\s*/g, '');

  names.push(name);
  symbols.push(
    `  <symbol id="${name}" viewBox="${viewBox}" fill="none" stroke="currentColor" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round">${inner}</symbol>`
  );
}

const spriteContent = `<svg xmlns="http://www.w3.org/2000/svg">\n${symbols.join('\n')}\n</svg>\n`;

const typesContent = `// Auto-generated by scripts/build-icons.mjs from web/icons/*.svg. Do not edit manually.
export const ICON_NAMES = [
${names.map((n) => `  '${n}',`).join('\n')}
] as const;

export type IconName = (typeof ICON_NAMES)[number];
`;

function writeIfChanged(filePath, content) {
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  if (fs.existsSync(filePath) && fs.readFileSync(filePath, 'utf8') === content) {
    return;
  }
  fs.writeFileSync(filePath, content, 'utf8');
}

writeIfChanged(spriteOut, spriteContent);
writeIfChanged(typesOut, typesContent);
